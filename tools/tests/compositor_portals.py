#!/usr/bin/env python3
"""Exercise real output capture and portal cancellation on the private display.

Run through tools/dev/compositor-test-display.py with a Python environment
containing dbus-python, PyGObject and Pillow. OHMANSY_PORTAL_TOOLS must point to
a package containing xdg-desktop-portal, its wlr/gtk backends, grim and PipeWire.
"""
from contextlib import ExitStack
import os
from pathlib import Path
import subprocess
import time

import dbus
from dbus.mainloop.glib import DBusGMainLoop
from gi.repository import GLib
from PIL import Image

from compositor_support import Control, ensure_test_display, wait_for


def run():
    ensure_test_display()
    assert os.environ['OHMANSY_TEST_DISPLAY'] == 'headless'
    tools = Path(os.environ['OHMANSY_PORTAL_TOOLS'])
    control = Control(os.environ['OHMANSY_COMPOSITOR_CONTROL'])
    with ExitStack() as stack:
        root = Path(os.environ['XDG_STATE_HOME']) / 'portal-test'
        root.mkdir(exist_ok=True)
        print(f'Portal logs: {root}', flush=True)
        env = dict(os.environ, XDG_CURRENT_DESKTOP='ohmansy', XDG_SESSION_DESKTOP='ohmansy')
        config = Path(env['XDG_CONFIG_HOME']) / 'xdg-desktop-portal'
        config.mkdir(exist_ok=True)
        (config / 'ohmansy-portals.conf').write_text(
            '[preferred]\ndefault=gtk\norg.freedesktop.impl.portal.ScreenCast=wlr\n')
        # This is the same chooser command generated by compositor.nix.
        chooser = root / 'wlr.ini'
        chooser.write_text('[screencast]\nmax_fps=30\nchooser_type=dmenu\n'
            f"chooser_cmd={tools}/bin/wofi --normal-window --dmenu --prompt 'Share a display or window'\n")
        env['NIX_XDG_DESKTOP_PORTAL_DIR'] = str(tools / 'share/xdg-desktop-portal/portals')

        def launch(command, name):
            log = stack.enter_context((root / name).open('w'))
            process = subprocess.Popen(command, env=env, stdout=log, stderr=log)
            def stop():
                if process.poll() is None:
                    process.terminate()
                    process.wait(timeout=10)
            stack.callback(stop)
            return process

        # First verify the actual shm copy path, not just protocol advertisement.
        png = root / 'output.png'
        subprocess.run([str(tools / 'bin/grim'), str(png)], env=env, check=True, timeout=15)
        with Image.open(png) as image:
            assert image.width > 0 and image.height > 0
            assert image.convert('RGB').getextrema() != ((0, 0), (0, 0), (0, 0))
            print(f'Shm output capture: {image.size}', flush=True)

        DBusGMainLoop(set_as_default=True)
        bus = dbus.SessionBus()
        launch([str(tools / 'bin/pipewire')], 'pipewire.log')
        wait_for(lambda: (Path(env['XDG_RUNTIME_DIR']) / 'pipewire-0').exists())
        policy = Path(env['XDG_CONFIG_HOME']) / 'wireplumber/wireplumber.conf.d'
        policy.mkdir(parents=True)
        (policy / 'no-devices.conf').write_text('''wireplumber.profiles = {
  main = {
    monitor.alsa = disabled
    monitor.bluez = disabled
    monitor.v4l2 = disabled
    monitor.libcamera = disabled
  }
}
''')
        launch([str(tools / 'bin/wireplumber')], 'wireplumber.log')
        backend = launch([str(tools / 'libexec/xdg-desktop-portal-wlr'), '--loglevel=DEBUG', '--config', str(chooser)], 'wlr.log')
        def backend_ready():
            assert backend.poll() is None, (backend.returncode, (root / 'wlr.log').read_text())
            return bus.name_has_owner('org.freedesktop.impl.portal.desktop.wlr')
        wait_for(backend_ready)
        launch([str(tools / 'libexec/xdg-desktop-portal-gtk')], 'gtk.log')
        wait_for(lambda: bus.name_has_owner('org.freedesktop.impl.portal.desktop.gtk'))
        launch([str(tools / 'libexec/xdg-desktop-portal')], 'portal.log')
        wait_for(lambda: bus.name_has_owner('org.freedesktop.portal.Desktop'))
        result = subprocess.check_output(['busctl', '--user', 'introspect',
            'org.freedesktop.portal.Desktop', '/org/freedesktop/portal/desktop',
            'org.freedesktop.portal.ScreenCast'], env=env, text=True)
        assert 'CreateSession' in result and 'SelectSources' in result and 'Start' in result, result
        print(result, flush=True)
        proxy = bus.get_object('org.freedesktop.portal.Desktop', '/org/freedesktop/portal/desktop')
        xml = dbus.Interface(proxy, 'org.freedesktop.DBus.Introspectable').Introspect()
        assert 'org.freedesktop.portal.FileChooser' in xml
        portal = dbus.Interface(proxy, 'org.freedesktop.portal.ScreenCast')
        assert int(dbus.Interface(proxy, 'org.freedesktop.DBus.Properties').Get(
            'org.freedesktop.portal.ScreenCast', 'AvailableSourceTypes')) == 3
        responses = {}
        def received(code, results, path=None):
            responses[str(path)] = (int(code), results)
        bus.add_signal_receiver(received, signal_name='Response',
            dbus_interface='org.freedesktop.portal.Request', path_keyword='path')

        def pump():
            context = GLib.MainContext.default()
            while context.pending():
                context.iteration(False)

        def response(path):
            def poll():
                pump()
                return responses.get(str(path))
            return wait_for(poll, description='portal response')

        # A real PipeWire consumer verifies pixels, not just the WINDOW bit.
        # Every graphical client and the capture bus remain on the private display.
        fixture = root / 'fixture.qml'
        fixture.write_text('''import QtQuick
import Quickshell
import Quickshell.Io
ShellRoot {
    IpcHandler {
        target: "capture-fixture"
        function showPopup(show: bool): void { popup.visible = show; }
    }
    FloatingWindow {
        id: targetWindow
        title: "Capture fixture"
        visible: true
        implicitWidth: 700; implicitHeight: 500
        Rectangle {
            anchors.fill: parent
            SequentialAnimation on color {
                loops: Animation.Infinite
                ColorAnimation { from: "#a02020"; to: "#f02020"; duration: 500 }
                ColorAnimation { from: "#f02020"; to: "#a02020"; duration: 500 }
            }
        }
    }
    PopupWindow {
        id: popup
        anchor.window: targetWindow
        anchor.rect.x: 100; anchor.rect.y: 100
        implicitWidth: 100; implicitHeight: 80
        color: "#2222ff"
    }
    FloatingWindow {
        title: "Unrelated green fixture"
        visible: true
        implicitWidth: 700; implicitHeight: 500
        color: "#00ff00"
    }
}''')
        fixture_process = launch(['quickshell', '--path', str(fixture)], 'fixture.log')
        target = wait_for(lambda: next((w for w in control()['windows']
            if w['title'] == 'Capture fixture' and w['surface_size']), None))
        wait_for(lambda: next((w for w in control()['windows']
            if w['title'] == 'Unrelated green fixture' and w['surface_size']), None))
        env['GST_PLUGIN_SYSTEM_PATH_1_0'] = str(tools / 'lib/gstreamer-1.0')
        env['GST_DEBUG'] = '2'

        def open_share(label, source_type):
            code, data = response(portal.CreateSession({
                'session_handle_token': label, 'handle_token': label + 'create'}))
            assert code == 0, (code, data)
            session = data['session_handle']
            before = {w['id'] for w in control()['windows']}
            request = portal.SelectSources(session, {
                'handle_token': label + 'select', 'types': dbus.UInt32(source_type),
                'multiple': False, 'cursor_mode': dbus.UInt32(1)})
            picker = wait_for(lambda: next((w for w in control()['windows']
                if w['id'] not in before and 'wofi' in w.get('app_id', '').lower()), None))
            control('focus', picker['id'])
            if source_type == 2:
                control.send_keys([46, 30, 25, 20, 22, 19, 18])  # Filter "capture".
                time.sleep(.3)  # Wofi applies its search filter asynchronously.
            control.send_keys([108, 28])
            code, data = response(request)
            assert code == 0, (code, data)
            # Closing the chooser can reconfigure the selected window. Let that
            # settle before asking a new consumer to negotiate its initial size.
            wait_for(lambda: all(w['id'] != picker['id'] for w in control()['windows']))
            time.sleep(.3)
            code, data = response(portal.Start(session, '', {'handle_token': label + 'start'}))
            assert code == 0 and len(data['streams']) == 1, (code, data)
            node, properties = data['streams'][0]
            assert int(properties['source_type']) == source_type, properties
            fd = portal.OpenPipeWireRemote(session, {}).take()
            directory = root / label
            directory.mkdir()
            log = stack.enter_context((directory / 'consumer.log').open('w'))
            consumer = subprocess.Popen([str(tools / 'bin/gst-launch-1.0'), '-e',
                'pipewiresrc', f'fd={fd}', f'path={node}', 'do-timestamp=true',
                '!', 'videoconvert', '!', 'pngenc', '!', 'multifilesink',
                f'location={directory}/frame-%04d.png'], env=env, pass_fds=(fd,), stdout=log, stderr=log)
            os.close(fd)
            stack.callback(lambda: consumer.poll() is None and consumer.terminate())
            def images():
                assert consumer.poll() is None, (directory / 'consumer.log').read_text()
                return sorted(directory.glob('frame-*.png'))
            wait_for(lambda: len(images()) >= 5, timeout=20, description=f'{label} PipeWire frames')
            return session, consumer, directory, images

        def close_share(session, consumer):
            dbus.Interface(bus.get_object('org.freedesktop.portal.Desktop', session),
                           'org.freedesktop.portal.Session').Close()
            if consumer.poll() is None:
                consumer.terminate()
            consumer.wait(timeout=10)

        session, consumer, directory, images = open_share('window', 2)
        with Image.open(images()[0]) as image:
            initial_size = image.size
            state = control()
            current = next(w for w in state['windows'] if w['id'] == target['id'])
            scale = next(o['scale'] for o in state['outputs'] if o['name'] == current['output'])
            assert all(abs(actual - logical * scale) <= 1 for actual, logical in
                       zip(image.size, current['surface_size'])), (image.size, current)
            assert not any(g > 200 and r < 60 and b < 60 for r, g, b in
                           image.convert('RGB').resize((200, 200)).get_flattened_data()), 'Unrelated window leaked into capture'
            r, g, b = image.convert('RGB').getpixel((image.width // 2, image.height // 2))
            assert r > 100 and g < 60 and b < 60, (r, g, b)
            # Correct buffer dimensions alone can hide an unscaled image drawn
            # into a larger black target. Check content near the far edge too.
            r, g, b = image.convert('RGB').getpixel((int(image.width * .9), int(image.height * .9)))
            assert r > 100 and g < 60 and b < 60, (r, g, b)
        # Capture must remain independent of focus, workspace and occlusion.
        control('focus', target['id'])
        start = len(images())
        subprocess.run(['quickshell', 'ipc', '--pid', str(fixture_process.pid),
            'call', 'capture-fixture', 'showPopup', 'true'], env=env, check=True, timeout=10)
        def has_popup():
            for path in images()[start:]:
                with Image.open(path) as image:
                    if any(b > 200 and r < 60 and g < 60 for r, g, b in
                           image.convert('RGB').resize((100, 100)).get_flattened_data()):
                        return True
            return False
        wait_for(has_popup, description='selected window popup appears in capture')
        subprocess.run(['quickshell', 'ipc', '--pid', str(fixture_process.pid),
            'call', 'capture-fixture', 'showPopup', 'false'], env=env, check=True, timeout=10)
        control('resize', -100)
        wait_for(lambda: any(Image.open(p).size != initial_size for p in images()),
                 description='capture renegotiates after window resize')
        control('workspace', 4)
        before = len(images())
        wait_for(lambda: len(images()) > before + 8, description='hidden window continues streaming')
        colors = set()
        for path in images()[before:]:
            with Image.open(path) as image:
                pixel = image.convert('RGB').getpixel((image.width // 2, image.height // 2))
                assert pixel[0] > 100 and pixel[1] < 60 and pixel[2] < 60, pixel
                colors.add(pixel)
        assert len(colors) > 1, 'Hidden captured window stopped animating'
        close_share(session, consumer)
        control('workspace', 1)
        code, data = response(portal.CreateSession({
            'session_handle_token': 'cancelwindow', 'handle_token': 'cancelwindowcreate'}))
        assert code == 0, (code, data)
        before = {w['id'] for w in control()['windows']}
        request = portal.SelectSources(data['session_handle'], {
            'handle_token': 'cancelwindowselect', 'types': dbus.UInt32(2)})
        picker = wait_for(lambda: next((w for w in control()['windows']
            if w['id'] not in before and 'wofi' in w.get('app_id', '').lower()), None))
        control('focus', picker['id'])
        control.send_keys([1])
        assert response(request)[0] == 1
        session, consumer, _, _ = open_share('window_repeat', 2)
        closed = []
        bus.add_signal_receiver(lambda *args: closed.append(True), signal_name='Closed',
            dbus_interface='org.freedesktop.portal.Session', path=str(session))
        fixture_process.terminate()
        fixture_process.wait(timeout=10)
        wait_for(lambda: (pump(), bool(closed))[1], description='closing the captured app ends its session')
        if consumer.poll() is None:
            consumer.terminate()
        consumer.wait(timeout=10)
        session, consumer, _, _ = open_share('monitor', 1)
        close_share(session, consumer)
        print('PipeWire frames: isolated window pixels, popup, resize, hidden-workspace animation, cancellation, repeated sharing, app closure and display capture passed.', flush=True)

        code, data = response(portal.CreateSession({
            'session_handle_token': 'trial', 'handle_token': 'create'}))
        assert code == 0, (code, data)
        session = data['session_handle']
        before = {w['id'] for w in control()['windows']}
        request = portal.SelectSources(session, {
            'handle_token': 'select', 'types': dbus.UInt32(1),
            'multiple': False, 'cursor_mode': dbus.UInt32(1)})
        picker = wait_for(lambda: next((w for w in control()['windows']
            if w['id'] not in before and 'wofi' in w.get('app_id', '').lower()), None),
            description='system display chooser')
        # Focus and highlight a supported display, then cancel without accepting
        # the choice. wlr opens its picker in SelectSources. Start and
        # OpenPipeWireRemote are deliberately never requested.
        control('focus', picker['id'])
        control.send_keys([108])  # Down selects a display in the list.
        control.send_keys([1])    # Escape cancels before consent.
        code, data = response(request)
        assert code == 1 and 'streams' not in data, (code, data)
        wait_for(lambda: all(w['id'] != picker['id'] for w in control()['windows']))
        # Also accept a supported display, then close the session before Start.
        code, data = response(portal.CreateSession({
            'session_handle_token': 'selected', 'handle_token': 'create2'}))
        assert code == 0, (code, data)
        session = data['session_handle']
        before = {w['id'] for w in control()['windows']}
        request = portal.SelectSources(session, {
            'handle_token': 'select2', 'types': dbus.UInt32(1), 'multiple': False})
        picker = wait_for(lambda: next((w for w in control()['windows']
            if w['id'] not in before and 'wofi' in w.get('app_id', '').lower()), None))
        control('focus', picker['id'])
        control.send_keys([108, 28])  # Down, Enter.
        code, data = response(request)
        assert code == 0 and 'streams' not in data, (code, data)
        dbus.Interface(bus.get_object('org.freedesktop.portal.Desktop', session),
            'org.freedesktop.portal.Session').Close()
        print('ScreenCast picker: Escape cancels; display selection can close before Start. FileChooser retained.', flush=True)


if __name__ == '__main__':
    run()
